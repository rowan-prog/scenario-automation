# ── docx ─────────────────────────────────────────────
BLACK = RGBColor(0x1A, 0x1A, 0x1A)
GREY = RGBColor(0x86, 0x86, 0x86)
CNC = RGBColor(0x5F, 0x6B, 0x7A)
ACC = RGBColor(0x8A, 0x5A, 0x10)
STAGE = RGBColor(0x44, 0x44, 0x44)
LINE = RGBColor(0xD8, 0xCB, 0xB0)

MD = re.compile(r'(\*\*[^*]+\*\*)')
IS_EP = re.compile(r'^第\s*\d+\s*集$')
IS_SCENE = re.compile(r'^\d{3}-\d')
IS_CAST = re.compile(r'^(人物|인물)')


def build(path, bilingual):
    d = docx.Document()
    s = d.sections[0]
    s.left_margin = s.right_margin = Cm(2.3)
    s.top_margin = s.bottom_margin = Cm(1.9)

    def para(after=0, before=0, keep=False, indent=0, spacing=1.32):
        p = d.add_paragraph()
        pf = p.paragraph_format
        pf.space_after = Pt(after)
        pf.space_before = Pt(before)
        pf.line_spacing = spacing
        pf.keep_with_next = keep
        if indent:
            pf.left_indent = Pt(indent)
        return p

    def run(p, text, *, cnfont=False, size=11, color=BLACK, bold=False):
        r = p.add_run(text)
        r.font.size = Pt(size)
        r.font.color.rgb = color
        r.bold = bold
        name = '微软雅黑' if cnfont else '맑은 고딕'
        r.font.name = name
        r._element.rPr.rFonts.set(qn('w:eastAsia'), name)
        return r

    def krline(p, text, size=11, color=BLACK):
        for seg in MD.split(text):
            if not seg:
                continue
            run(p, seg[2:-2] if seg.startswith('**') else seg,
                size=size, color=(ACC if seg.startswith('**') else color),
                bold=seg.startswith('**'))

    # 표지
    t = para(after=3)
    t.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run(t, '거지 알라딘과 요술램프', size=19, bold=True)
    t2 = para(after=3)
    t2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run(t2, '《乞丐阿拉丁与神灯》', cnfont=True, size=12, color=CNC)
    t3 = para(after=2)
    t3.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run(t3, '무료회차 1~8화  ·  ' + ('한국어 / 中文 대조본' if bilingual else '한국어 번역본'),
        size=10, color=GREY)

    first = True
    for c, k in zip(cn, kr):
        if IS_EP.match(c):
            if not first:
                d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
            first = False
            h = para(after=3, before=6, keep=True)
            run(h, k.lstrip('# '), size=17, bold=True)
            if bilingual:
                run(h, '   ' + c, cnfont=True, size=11, color=CNC)
            ln = para(after=10)
            run(ln, '─' * 44, size=8, color=LINE)
        elif IS_SCENE.match(c):
            h = para(before=15, after=2, keep=True)
            run(h, k.lstrip('# '), size=12.5, bold=True, color=ACC)
            if bilingual:
                h2 = para(after=2, keep=True)
                run(h2, c, cnfont=True, size=9.5, color=CNC)
        elif IS_CAST.match(c):
            p = para(after=9, keep=True)
            run(p, k, size=9.5, color=GREY)
            if bilingual:
                p2 = para(after=9, keep=True)
                run(p2, c, cnfont=True, size=9, color=CNC)
        else:
            dialogue = k.startswith('**')
            p = para(after=(2 if bilingual else (7 if dialogue else 5)),
                     before=(5 if dialogue else 0), keep=bilingual)
            krline(p, k, size=(11.5 if dialogue else 10.5),
                   color=(BLACK if dialogue else STAGE))
            if bilingual:
                p2 = para(after=(8 if dialogue else 6), indent=14)
                run(p2, c, cnfont=True, size=9.5, color=CNC)

    d.save(path)
    print('OK', os.path.basename(path))


