def set_font(run, size=None, bold=None, color=None):
    run.font.name = FONT
    run._element.get_or_add_rPr().get_or_add_rFonts().set(qn('w:eastAsia'), FONT)
    if size:
        run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    if color is not None:
        run.font.color.rgb = color


def translate():
    src = docx.Document(SRC)
    sp = src.paragraphs
    al = json.load(open(CODEX, encoding='utf-8'))
    if len(sp) != 328 or len(al) != 328:
        sys.exit(f'문단 수가 바뀜: 원고 {len(sp)} / Codex {len(al)}')
    rows = []
    for i, (p, a) in enumerate(zip(sp, al)):
        zh = p.text.strip()
        if zh != a['zh']:
            sys.exit(f'P{i:03d} 원고와 Codex 원문이 다름')
        ko = a['ko']
        for old, new in NAME_SUBS:
            ko = ko.replace(old, new)
        if i in FIX:
            ko = FIX[i]
        if bool(zh) != bool(ko):
            sys.exit(f'P{i:03d} 빈 줄 어긋남')
        if '\n' in ko:
            sys.exit(f'P{i:03d} 줄바꿈이 들어 있음(원고는 한 문단)')
        bold = any(r.bold for r in p.runs if r.text.strip())
        rows.append({'i': i, 'zh': zh, 'ko': ko, 'bold': bold,
                     'ep': bool(re.fullmatch(r'第\s*\d+\s*集', zh))})
    return rows


def main():
    rows = translate()
    d = docx.Document()
    sec = d.sections[0]
    sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
    sec.top_margin, sec.bottom_margin = Cm(2.0), Cm(2.0)
    sec.left_margin, sec.right_margin = Cm(2.2), Cm(2.2)
    normal = d.styles['Normal']
    normal.font.name = FONT
    normal.font.size = Pt(10.5)
    normal.element.get_or_add_rPr().get_or_add_rFonts().set(qn('w:eastAsia'), FONT)
    normal.paragraph_format.space_after = Pt(3)
    normal.paragraph_format.line_spacing = 1.15

    # 맨 앞 안내 (본문 문단 수에서 뺀다)
    h = d.add_paragraph()
    set_font(h.add_run('One Night with the Dragon Lord: The Dragon Eggs — 작가 대본 1023 · 1~8화 · 한국어 번역본'), 13, True)
    for n in NOTES:
        q = d.add_paragraph()
        set_font(q.add_run('· ' + n), 9.5, False, GREY)
    d.add_paragraph()
    n_front = len(d.paragraphs)

    runs = {}
    for r in rows:
        p = d.add_paragraph()
        if r['ko']:
            run = p.add_run(r['ko'])
            if r['ep']:
                set_font(run, 13, True)
                p.paragraph_format.space_before = Pt(12)
            else:
                set_font(run, None, r['bold'])
            runs[r['i']] = run

    for i, paras in COMMENTS:
        if i not in runs:
            sys.exit(f'P{i:03d} 빈 문단에 말풍선')
        for t in paras:
            if '→' in t:
                sys.exit(f'P{i:03d} 말풍선에 화살표')
        cm = d.add_comment(runs[i], text=paras[0], author='검토', initials='검')
        for t in paras[1:]:
            cm.add_paragraph(t)
    d.save(OUT)

    with open(OUT_TXT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(r['ko'] for r in rows) + '\n')

    # ── 검증 ──
    chk = docx.Document(OUT)
    body = chk.paragraphs[n_front:]
    src_n = len(docx.Document(SRC).paragraphs)
    body_txt = [p.text for p in body]
    errs = []
    if len(body) != src_n:
        errs.append(f'문단 수 {len(body)} != 원고 {src_n}')
    for k, (a, r) in enumerate(zip(body_txt, rows)):
        if a != r['ko']:
            errs.append(f'P{k:03d} 저장본 글자 다름')
        if bool(a) != bool(r['zh']):
            errs.append(f'P{k:03d} 빈 줄 어긋남')
    alltxt = '\n'.join(body_txt)
    for b in BANNED:
        if b in alltxt:
            errs.append(f'남은 표기 {b!r} {alltxt.count(b)}곳')
    for i, s in REVERT_CHECK.items():
        if s not in body_txt[i]:
            errs.append(f'P{i:03d} 되돌림 확인 실패: {s}')
    n_cm = len(list(chk.comments))
    if n_cm != len(COMMENTS):
        errs.append(f'말풍선 {n_cm} != {len(COMMENTS)}')
    print('본문 문단', len(body), '/ 원고', src_n, '/ 빈 문단', sum(1 for t in body_txt if not t),
          '/ 교체 줄', len(FIX), '/ 말풍선', n_cm, '/ 말풍선 단 줄', len({i for i, _ in COMMENTS}),
          '/ 에드릭', alltxt.count('에드릭'), '/ 섭정공', alltxt.count('섭정공'))
    if errs:
        print('\n'.join(errs))
        sys.exit(1)
    print('OK', OUT)


if __name__ == '__main__':
    main()
